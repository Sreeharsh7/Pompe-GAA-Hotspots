"""Stage 10: write results/RESULTS_REPORT.md with every number quoted in the manuscript.

All values come from results/values.json, which earlier stages populate.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd

from gaa_hotspot.common import MODEL_NAMES, MODEL_ORDER, ROOT, config, load_values, table

V = load_values()
cfg = config()
n, g, m, h, s, b = V["network"], V["network_groups"], V["models"], V["hotspots"], V["sss"], V["benchmark"]
imp = V.get("importance", {})


def p_fmt(p: float) -> str:
    if p < 1e-4:
        return f"{p:.2e}"
    return f"{p:.4f}"


L = []
w = L.append
w("# Results report — GAA structural hotspot analysis\n")
w("Generated by `scripts/10_report.py` from `results/values.json`. Every number below is produced by the pipeline in this repository.\n")

w("## 1. Dataset and residue interaction network\n")
w(f"- Structure: PDB 5NN3 (Rosetta-relaxed), chain A, residues {n['residue_range'][0]}–{n['residue_range'][1]}; **{n['n_residues']} resolved residues**.")
w(f"- RIN: **{n['n_nodes']} nodes, {n['n_edges_unique_pairs']:,} unique residue–residue contacts** ({n['n_typed_interactions']:,} typed RINerator interactions; one connected component).")
w(f"- Labels: **{n['n_mutation_positions']} reported missense-mutation positions** and {n['n_no_mutation']} positions without a reported mutation ({100 * n['n_mutation_positions'] / n['n_residues']:.1f}% positive).")
w(f"- All residues retained; {n['n_zero_betweenness']} residues with zero betweenness enter as log10(1 + 0) = 0. Missing φ/ψ values ({n['missing_feature_values']}) are median-imputed inside each training fold.\n")

w("## 2. Network centrality and criticality\n")
lo, hi = g["centrality_spearman_range"]
w(f"- Spearman correlation among the seven centralities ranges from {lo:.2f} to {hi:.2f} (Burt's constraint is negatively correlated with the others).")
for k in ["HDHB", "LDHB", "LDLB"]:
    gg = g["groups"][k]
    w(f"- **{k}: {gg['n']} residues**, of which {gg['n_mutation_positions']} ({100 * gg['fraction_mutated']:.1f}%) are reported mutation positions.")
w(f"- **Supercritical hubs (10)**: {', '.join(g['supercritical_hubs'])}. All 10 fall in the HDHB group.")
w(f"- **{g['n_supercritical_mutated']} of 10 hubs are reported mutation positions** ({', '.join(g['supercritical_mutation_positions'])}); these are {100 * g['fraction_mutation_positions_that_are_hubs']:.1f}% of all {n['n_mutation_positions']} mutation positions.")
w(f"- Sensitivity: with z-scored axes the hub set is {', '.join(g['supercritical_hubs_zscored'])} ({g['n_hubs_shared_raw_vs_z']}/10 shared).")
gm = g["group_medians"]
w(f"- Median SASA (Å²): HDHB {gm['HDHB']['areaSAS_median']:.1f}, LDHB {gm['LDHB']['areaSAS_median']:.1f}, LDLB {gm['LDLB']['areaSAS_median']:.1f}, SC {gm['SC']['areaSAS_median']:.1f} (Kruskal–Wallis across HDHB/LDHB/LDLB P = {p_fmt(g['kruskal_areaSAS_p'])}).")
w(f"- Median ConSurf score: HDHB {gm['HDHB']['conservation_median']:.2f}, LDHB {gm['LDHB']['conservation_median']:.2f}, LDLB {gm['LDLB']['conservation_median']:.2f}, SC {gm['SC']['conservation_median']:.2f} (P = {p_fmt(g['kruskal_conservation_p'])}).")
fs = pd.read_csv(table("feature_statistics.csv"))
w(f"- {g['n_features_significant_q05']} of {len(fs)} features differ between mutation positions and other residues at q < 0.05 (permutation test, 10,000 permutations, BH correction):\n")
w("| Feature | Mean (mutation) | Mean (other) | Cohen's d | Permutation P | q (BH) |")
w("|---|---:|---:|---:|---:|---:|")
for r in fs.itertuples():
    w(f"| {r.feature} | {r.mean_mutation_positions:.4g} | {r.mean_other:.4g} | {r.cohens_d:.2f} | {'< 1e-4' if r.permutation_p < 2e-4 else f'{r.permutation_p:.4f}'} | {'< 1e-4' if r.permutation_q_bh < 2e-4 else f'{r.permutation_q_bh:.4f}'} |")
w("")

w("## 3. Ensemble classifiers (repeated nested cross-validation)\n")
w(f"- {m['n_residues']} residues ({m['n_positive']} positive, {m['n_negative']} negative), 14 features; {m['repeats']} × {m['outer_folds']}-fold outer CV, {m['inner_folds']}-fold inner grid search (ROC AUC). Median imputation, standardisation and ADASYN are fitted inside training folds only.\n")
w("| Model | Pooled OOF ROC AUC (95% CI) | Per-repeat AUC, mean ± SD | Sensitivity | Specificity | MCC |")
w("|---|---|---|---:|---:|---:|")
for k in MODEL_ORDER:
    p = m["performance"][k]
    w(f"| {MODEL_NAMES[k]} | **{p['pooled_oof_auc']:.3f}** ({p['auc_ci_low']:.3f}–{p['auc_ci_high']:.3f}) | {p['per_repeat_auc_mean']:.3f} ± {p['per_repeat_auc_sd']:.3f} | {p['sensitivity']:.3f} | {p['specificity']:.3f} | {p['mcc']:.3f} |")
aucs = [m["performance"][k]["pooled_oof_auc"] for k in MODEL_ORDER]
w(f"\n- ROC AUC range: **{min(aucs):.2f}–{max(aucs):.2f}**. Best model: {MODEL_NAMES[m['best_model']]}.")
w(f"- DeLong tests, {MODEL_NAMES[m['best_model']]} vs:")
for k, d in m["delong"].items():
    w(f"  - {MODEL_NAMES[k]}: ΔAUC = {d['difference']:+.3f}, P = {p_fmt(d['p'])} (Holm {p_fmt(d['p_holm'])})")
if "legacy811_models" in V:
    lm = V["legacy811_models"]
    w(f"- Sensitivity (original 811-residue subset): " + ", ".join(f"{MODEL_NAMES[k]} {lm['performance'][k]['pooled_oof_auc']:.3f}" for k in MODEL_ORDER) + ".")
if imp:
    w(f"- Top features by held-out permutation importance: {', '.join(imp['permutation_top5'])}; by SHAP: {', '.join(imp['shap_top5'])}.")
w("")

if "ablation" in V:
    w("Feature-group ablation (nested CV, 2 repeats; pooled OOF AUC, DeLong P vs all 14 features):\n")
    w("| Feature set | LR | XGBoost |")
    w("|---|---|---|")
    sets = dict.fromkeys(k.split(" | ")[0] for k in V["ablation"])
    for fs_ in sets:
        cells = []
        for mm in ["lr", "xgb"]:
            a_ = V["ablation"][f"{fs_} | {mm}"]
            pv = a_.get("p_vs_all")
            cells.append(f"{a_['auc']:.3f} ({a_['lo']:.3f}–{a_['hi']:.3f})" + ("" if pv is None or pv != pv else f", P = {p_fmt(pv)}"))
        w(f"| {fs_} | {cells[0]} | {cells[1]} |")
    w("")

w("## 4. Consensus hotspots\n")
w(f"- Vote rule: {h['vote_rule']} (thresholds: " + ", ".join(f"{MODEL_NAMES[k]} {v:.3f}" for k, v in h['vote_thresholds'].items()) + f"); consensus = ≥ {h['consensus_min_votes']} of 5 models.")
w(f"- Residues flagged by ≥ 1 model: **{h['n_flagged_by_at_least_one_model']}**.")
w(f"- Consensus residues: **{h['n_consensus']}** = {h['n_consensus_known']} known mutation positions + **{h['n_novel']} novel consensus hotspots**.")
w(f"- Known mutation positions below consensus: {h['n_known_below_consensus']} (of which {h['n_known_zero_votes']} received no vote). Consensus recovers {100 * h['consensus_recall_of_known_positions']:.1f}% of known positions.")
w(f"- Novel hotspots by vote count: {h['novel_vote_distribution']}; {h['novel_consensus_in_all_repeats']}/{h['n_novel']} reach consensus in every CV repeat.")
w(f"- Novel hotspots: {', '.join(h['novel_residues'])}.")
w(f"- Novel hotspots that are themselves annotated active-site residues: {', '.join(h['novel_active_site_residues']) or 'none'}; {h['novel_within_8A_of_active_site']} lie within 8 Å of an active-site residue.")
w(f"- Overlap with the 42-position list in manuscript draft v7: {h['v7_42_hotspots_reproduced']}/42 reproduced.\n")
w("Sensitivity of the hotspot set to the vote rule:\n")
w("| Vote rule | Flagged by ≥1 model | Consensus | Known | Novel | Novel with 5/5 |")
w("|---|---:|---:|---:|---:|---:|")
for r in h["vote_threshold_sensitivity"]:
    w(f"| {r['vote_rule']} | {r['flagged_by_at_least_one_model']} | {r['consensus']} | {r['consensus_known_positions']} | {r['novel_consensus_hotspots']} | {r['novel_with_5_votes']} |")
w("")
dom = pd.read_csv(table("hotspot_domain_breakdown.csv"))
w("| Domain | Range | Residues | Novel hotspots | % of novel | Expected by size | Binomial P |")
w("|---|---|---:|---:|---:|---:|---:|")
for r in dom.itertuples():
    w(f"| {r.domain} | {r.range} | {r.residues_in_structure} | {r.novel_hotspots} | {r.percent_of_novel:.1f} | {r.expected_by_size:.1f} | {r.binomial_p:.3f} |")
w("")
d = h["discordant"]
w(f"- Known positions with zero votes vs known consensus positions (medians): SASA {d['areaSAS']['median_zero_vote_positions']:.1f} vs {d['areaSAS']['median_consensus_positions']:.1f} Å² (P = {p_fmt(d['areaSAS']['mann_whitney_p'])}); "
  f"ConSurf {d['conservation']['median_zero_vote_positions']:.2f} vs {d['conservation']['median_consensus_positions']:.2f} (P = {p_fmt(d['conservation']['mann_whitney_p'])}); "
  f"degree {d['degree']['median_zero_vote_positions']:.0f} vs {d['degree']['median_consensus_positions']:.0f} (P = {p_fmt(d['degree']['mann_whitney_p'])}).\n")

w("## 5. Substitution Severity Score\n")
w(f"- DI: {s['n_properties']} AAindex properties ({s['n_properties_imputed']} with one missing value, mean-imputed), standardised; PCA retains **{s['n_components']} components ({100 * s['variance_retained']:.2f}% variance)**. Pearson r with the legacy DI matrix = {s['pearson_r_vs_legacy_DI']:.3f}.")
w(f"- EVOscore from ConSurf alignment frequencies at {s['n_positions']} positions; {s['n_substitutions']:,} substitutions scored; EVOscore range {s['evoscore_range'][0]:.2f} to {s['evoscore_range'][1]:.2f}; {100 * s['fraction_evoscore_at_cap']:.1f}% of substitutions involve a residue never observed in the alignment (EVOscore at cap).")
w(f"- Structure and ConSurf wild-type residues agree at every position (mismatches: {s['wt_mismatch_structure_vs_consurf'] or 'none'}).")
w(f"- SSS median {s['sss_median']:.3f} (IQR {s['sss_iqr'][0]:.3f}–{s['sss_iqr'][1]:.3f}).\n")

w("## 6. Benchmark against variant effect predictors\n")
cc = b["clinvar_class_counts"]
w(f"- ClinVar GAA missense variants: **{b['clinvar_variants_total']}** = {cc.get('Pathogenic', 0)} P/LP, {cc.get('Benign', 0)} B/LB, {cc.get('VUS', 0)} VUS, {cc.get('Conflicting', 0)} conflicting.")
w(f"- P/LP + B/LB: {b['binary_variants']}; within the resolved structure: {b['binary_in_structure']}. Coverage among these {b['binary_variants']}: {b['coverage_binary']}.")
w(f"- **Benchmark set (all four scores available): {b['benchmark_n']} variants = {b['benchmark_pathogenic']} P/LP + {b['benchmark_benign']} B/LB.**\n")
w("| Predictor | ROC AUC | DeLong 95% CI | Bootstrap 95% CI | Spearman r | Spearman P |")
w("|---|---:|---|---|---:|---:|")
for t in ["SSS", "AlphaMissense", "ESM-1v", "EVE", "EVOscore", "DI"]:
    p = b["performance"][t]
    name = t if t not in ("EVOscore", "DI") else f"{t} (SSS component)"
    w(f"| {name} | **{p['roc_auc']:.3f}** | {p['delong_ci_low']:.3f}–{p['delong_ci_high']:.3f} | {p['bootstrap_ci_low']:.3f}–{p['bootstrap_ci_high']:.3f} | {p['spearman_r']:.3f} | {p['spearman_p']:.2e} |")
w("\n- Paired DeLong tests (SSS vs …): " + "; ".join(f"{k.replace('SSS vs ', '')} ΔAUC {v['difference']:+.3f}, P = {v['p']:.3f}" for k, v in b["delong_vs_sss"].items()) + ".")
th = b["thresholds"]
f5 = th["fixed 0.5"]
w(f"- SSS ≥ 0.5: sensitivity {f5['sensitivity']:.3f} ({f5['TP']}/{f5['TP'] + f5['FN']}), specificity {f5['specificity']:.3f} ({f5['TN']}/{f5['TN'] + f5['FP']}), accuracy {f5['accuracy']:.3f}.")
yo = th["Youden optimum (in-sample)"]
w(f"- In-sample Youden threshold {yo['value']:.3f}: sensitivity {yo['sensitivity']:.3f}, specificity {yo['specificity']:.3f} (optimistic; same data).")
w(f"- VUS within the structure: {b['vus_in_structure']}; {b['vus_sss_ge_0.5']} have SSS ≥ 0.5.\n")

(ROOT / "results" / "RESULTS_REPORT.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
